#!/bin/bash

# Скрипт находит 10 самых частых слов в текстовом файле

file="$1"

# Проверка что файл существует 
if [[ ! -f "$file" ]]; then
  echo "Файл не найден!"
  exit 1
fi

# Читаем файл - переводим все в нижний регистр - разбиваем текст на слова
# сортируем по алфавиту-подсчитываем повторения и сортируем по убыванию
# Далее берм 10 самых частых
cat "$file" \
  | tr '[:upper:]' '[:lower:]' \ 
  | tr -cs '[:alpha:]' '\n' \ 
  | sort \ 
  | uniq -c \ 
  | sort -nr \ 
  | head -10


